/**
 * shipout init — Plutonium-style generator.
 *
 * Scaffolds Shipout security into a project: a shipout.config.json
 * declaration, a GitHub Actions workflow, and prints the remaining
 * manual steps. The scanning engine itself stays a CLI tool; this
 * generates everything around it so the developer never hand-writes
 * security plumbing.
 */
import * as fs from 'fs';
import * as path from 'path';
import * as readline from 'readline';

export interface InitOptions {
    target?: string;
    failOn?: string;
    force?: boolean;
    yes?: boolean;
}

const VALID_LEVELS = ['info', 'low', 'medium', 'high', 'critical'];

const WORKFLOW_TEMPLATE = `name: Shipout security scan

# Generated by \`shipout init\`. Scans the target in shipout.config.json
# on every push to main, on pull requests, and weekly.
#
# THIS WORKFLOW NEEDS YOUR OWN CREDENTIALS TO RUN:
#   1. Your own Gemini API key as the GEMINI_API_KEY repository secret
#      (Settings > Secrets and variables > Actions). Free at
#      https://aistudio.google.com/app/apikey
#   2. Your own target URL in shipout.config.json, or set the
#      SHIPOUT_TARGET repository variable.

on:
  push:
    branches: [main]
  pull_request:
  schedule:
    - cron: '0 6 * * 1'
  workflow_dispatch:
    inputs:
      target:
        description: "URL to scan (overrides shipout.config.json)"
        required: false

jobs:
  scan:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4

      - uses: actions/setup-node@v4
        with:
          node-version: 20

      - name: Install Shipout
        run: |
          # Once shipout is published to npm this becomes: npm install -g shipout
          git clone --depth 1 https://github.com/valorm/shipout-oss.git /tmp/shipout-oss
          cd /tmp/shipout-oss && npm ci --no-audit --no-fund && npm run build

      - name: Run Shipout scan
        env:
          GEMINI_API_KEY: \${{ secrets.GEMINI_API_KEY }}
        run: |
          TARGET="\${{ inputs.target }}"
          if [ -z "$TARGET" ]; then TARGET=$(node -p "require('./shipout.config.json').target || ''"); fi
          if [ -z "$TARGET" ]; then TARGET="\${{ vars.SHIPOUT_TARGET }}"; fi
          if [ -z "$TARGET" ]; then
            echo "No scan target set. Run \`shipout init --target <url>\` or set the SHIPOUT_TARGET repository variable."
            exit 1
          fi
          if [ -z "$GEMINI_API_KEY" ]; then
            echo "GEMINI_API_KEY secret is not set. Add it under repository Settings > Secrets."
            exit 1
          fi
          FAIL_ON=$(node -p "require('./shipout.config.json').failOn || 'high'")
          node /tmp/shipout-oss/apps/cli/dist/apps/cli/src/index.js scan "$TARGET" --fail-on="$FAIL_ON"
`;

function flagValue(rawArgs: string[], name: string): string | undefined {
    const eq = rawArgs.find(a => a.startsWith(name + '='));
    if (eq) return eq.split('=').slice(1).join('=');
    const idx = rawArgs.indexOf(name);
    if (idx !== -1 && idx + 1 < rawArgs.length && !rawArgs[idx + 1].startsWith('--')) {
        return rawArgs[idx + 1];
    }
    return undefined;
}

function promptQuestion(query: string): Promise<string> {
    const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
    return new Promise(resolve => rl.question(query, ans => {
        rl.close();
        resolve(ans.trim());
    }));
}

function writeFile(filePath: string, content: string, force: boolean): 'created' | 'skipped' | 'overwritten' {
    const existed = fs.existsSync(filePath);
    if (existed && !force) return 'skipped';
    fs.mkdirSync(path.dirname(filePath), { recursive: true });
    fs.writeFileSync(filePath, content);
    return existed ? 'overwritten' : 'created';
}

export async function runInit(rawArgs: string[]): Promise<void> {
    const opts: InitOptions = {
        force: rawArgs.includes('--force'),
        yes: rawArgs.includes('--yes') || rawArgs.includes('-y'),
    };
    const targetFlag = flagValue(rawArgs, '--target');
    const failOnFlag = flagValue(rawArgs, '--fail-on');
    if (targetFlag) opts.target = targetFlag;
    if (failOnFlag) opts.failOn = failOnFlag.toLowerCase();

    console.log('\n🛡️  Shipout init — scaffolding security into this project\n');

    if (!opts.target && !opts.yes) {
        opts.target = await promptQuestion('URL to scan (e.g. https://staging.example.com): ');
    }
    if (!opts.target) {
        console.error('❌ A scan target is required. Usage: shipout init --target <url>');
        process.exit(1);
    }
    try {
        new URL(opts.target);
    } catch {
        console.error(`❌ Not a valid URL: ${opts.target}`);
        process.exit(1);
    }

    if (!opts.failOn && !opts.yes) {
        const level = await promptQuestion('Fail the build at which severity? (info/low/medium/high/critical) [high]: ');
        opts.failOn = level || 'high';
    }
    opts.failOn = (opts.failOn || 'high').toLowerCase();
    if (!VALID_LEVELS.includes(opts.failOn)) {
        console.error(`❌ Invalid level: ${opts.failOn}. Use one of: ${VALID_LEVELS.join(', ')}`);
        process.exit(1);
    }

    const cwd = process.cwd();
    const results: string[] = [];

    // 1. shipout.config.json — the single declaration everything reads.
    const configPath = path.join(cwd, 'shipout.config.json');
    const config = { target: opts.target, failOn: opts.failOn };
    const configState = writeFile(configPath, JSON.stringify(config, null, 2) + '\n', !!opts.force);
    results.push(`shipout.config.json — ${configState}`);

    // 2. GitHub Actions workflow.
    const workflowPath = path.join(cwd, '.github', 'workflows', 'shipout-scan.yml');
    const workflowState = writeFile(workflowPath, WORKFLOW_TEMPLATE, !!opts.force);
    results.push(`.github/workflows/shipout-scan.yml — ${workflowState}`);

    console.log('Generated:\n');
    for (const r of results) console.log(`  ${r}`);
    const skipped = results.filter(r => r.endsWith('skipped'));
    if (skipped.length > 0) {
        console.log('\n  (use --force to overwrite existing files)');
    }

    console.log(`
Before the scan can run, two things must be your own:

  1. Your own Gemini API key, saved as the GEMINI_API_KEY repository
     secret (Settings > Secrets and variables > Actions).
     Get one free at https://aistudio.google.com/app/apikey
  2. Your own target URL in shipout.config.json
     (currently set to ${opts.target}).

Then push to main or open a pull request and the scan runs automatically.
Change the target or severity any time in shipout.config.json.

Run \`shipout scan ${opts.target}\` to try a scan right now.
`);
}
