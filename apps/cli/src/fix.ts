import * as fs from 'fs';
import * as path from 'path';
import { Finding } from '../../../packages/shared/types/scan-context';

export type Framework = 'express' | 'nextjs' | 'fastify' | 'koa' | 'node' | 'unknown';

export function detectFramework(projectDir: string): Framework {
    const pkgPath = path.join(projectDir, 'package.json');
    if (!fs.existsSync(pkgPath)) return 'unknown';
    try {
        const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf-8'));
        const deps = { ...pkg.dependencies, ...pkg.devDependencies };
        if (deps['next']) return 'nextjs';
        if (deps['express']) return 'express';
        if (deps['fastify']) return 'fastify';
        if (deps['koa']) return 'koa';
        return 'node';
    } catch {
        return 'unknown';
    }
}

interface GeneratedFix {
    filename: string;
    content: string;
    appliesTo: string;
}

export function generateFixes(findings: Finding[], framework: Framework): GeneratedFix[] {
    const fixes: GeneratedFix[] = [];
    const types = new Set(findings.map(f => f.type));

    // Missing security headers -> middleware
    if (types.has('header_analysis')) {
        const missing = findings
            .filter(f => f.type === 'header_analysis' && f.description.includes('Missing'))
            .map(f => f.description);
        if (missing.length > 0) {
            fixes.push({
                filename: 'security-headers.js',
                appliesTo: 'Missing security headers',
                content: buildHeadersFix(framework, missing),
            });
        }
    }

    // Exposed .env -> gitignore + rotation guide
    const envExposed = findings.some(f =>
        f.type === 'sensitive_file_probe' && f.description.includes('/.env'));
    if (envExposed) {
        fixes.push({
            filename: '.gitignore.additions',
            appliesTo: 'Exposed .env file',
            content: `# Added by shipout fix — never commit secrets\n.env\n.env.local\n.env.production\n.env*.local\n`,
        });
        fixes.push({
            filename: 'ROTATE-SECRETS.md',
            appliesTo: 'Exposed .env file',
            content: buildRotationGuide(findings),
        });
    }

    // Exposed /debug -> removal guide
    const debugExposed = findings.some(f =>
        f.type === 'sensitive_file_probe' && f.description.includes('/debug'));
    if (debugExposed) {
        fixes.push({
            filename: 'REMOVE-DEBUG-ROUTE.md',
            appliesTo: 'Exposed /debug route',
            content: `# Remove or protect the /debug route\n\nShipout found /debug publicly reachable and leaking config.\n\n1. Delete the route entirely if it was for development only.\n2. If you need it, gate it behind authentication and IP allowlisting:\n   - Require an admin session\n   - Only respond on localhost, never in production\n   - Never include secrets, keys, or full environment dumps\n`,
        });
    }

    // Reflected XSS -> escaping helper
    const xss = findings.filter(f => f.type === 'xss_probe' || f.type === 'payload_fuzz');
    if (xss.length > 0) {
        const endpoints = [...new Set(xss.map(f => f.endpoint).filter(Boolean))];
        fixes.push({
            filename: 'escape-html.js',
            appliesTo: 'Reflected XSS',
            content: buildXssFix(framework, endpoints as string[]),
        });
    }

    // Permissive CORS -> restrictive config (INFO, optional)
    const cors = findings.some(f => f.type === 'cors_test');
    if (cors) {
        fixes.push({
            filename: 'cors-config.js',
            appliesTo: 'Permissive CORS (informational)',
            content: buildCorsFix(framework),
        });
    }

    return fixes;
}

function buildHeadersFix(framework: Framework, missing: string[]): string {
    const headerLines = [
        `res.setHeader('X-Frame-Options', 'DENY');`,
        `res.setHeader('X-Content-Type-Options', 'nosniff');`,
        `res.setHeader('Strict-Transport-Security', 'max-age=31536000; includeSubDomains');`,
        `res.setHeader('Content-Security-Policy', "default-src 'self'");`,
        `res.setHeader('Referrer-Policy', 'strict-origin-when-cross-origin');`,
    ].join('\n    ');

    if (framework === 'express') {
        return `// Generated by shipout fix — security headers middleware
// Missing: ${missing.join(', ')}
// Usage: app.use(securityHeaders);

function securityHeaders(req, res, next) {
    ${headerLines}
    next();
}

module.exports = securityHeaders;
`;
    }

    if (framework === 'nextjs') {
        return `// Generated by shipout fix — add to next.config.js
// Missing: ${missing.join(', ')}

const securityHeaders = [
  { key: 'X-Frame-Options', value: 'DENY' },
  { key: 'X-Content-Type-Options', value: 'nosniff' },
  { key: 'Strict-Transport-Security', value: 'max-age=31536000; includeSubDomains' },
  { key: 'Content-Security-Policy', value: "default-src 'self'" },
  { key: 'Referrer-Policy', value: 'strict-origin-when-cross-origin' },
];

// In next.config.js:
// async headers() {
//   return [{ source: '/(.*)', headers: securityHeaders }];
// }

module.exports = securityHeaders;
`;
    }

    return `// Generated by shipout fix — security headers
// Missing: ${missing.join(', ')}
// Add these headers to every response in your framework:

${headerLines.split('\n    ').join('\n')}
`;
}

function buildRotationGuide(findings: Finding[]): string {
    const exposed = findings
        .filter(f => f.type === 'sensitive_file_probe')
        .map(f => f.evidence)
        .flat()
        .filter(Boolean);
    return `# Rotate exposed secrets\n\nShipout found these files publicly reachable:\n${exposed.map(e => `- ${e}`).join('\n')}\n\nEvery secret in those files must be treated as compromised:\n\n1. Generate new values for each secret (API keys, database URLs, tokens)\n2. Update them in your hosting provider / secret manager\n3. Redeploy the app\n4. Revoke the old values at the provider\n5. Check git history: if the file was ever committed, the secrets are in\n   history forever. Rotate regardless of whether you delete the file now.\n`;
}

function buildXssFix(framework: Framework, endpoints: string[]): string {
    return `// Generated by shipout fix — HTML escaping helper
// Reflected XSS found at: ${endpoints.join(', ') || 'unknown endpoint'}
// Never interpolate user input into HTML without escaping.

function escapeHtml(str) {
    return String(str)
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;')
        .replace(/"/g, '&quot;')
        .replace(/'/g, '&#39;');
}

// Before (vulnerable):
//   res.send(\`<h1>Results for: \${req.query.q}</h1>\`);

// After:
//   res.send(\`<h1>Results for: \${escapeHtml(req.query.q)}</h1>\`);

module.exports = escapeHtml;
`;
}

function buildCorsFix(framework: Framework): string {
    if (framework === 'express') {
        return `// Generated by shipout fix — restrictive CORS
// Only allow your own frontend origin. CORS is not access control;
// real protection comes from authentication.

const cors = require('cors');

const allowedOrigins = ['https://yourapp.com'];

module.exports = cors({
    origin: (origin, cb) => {
        if (!origin || allowedOrigins.includes(origin)) cb(null, true);
        else cb(new Error('CORS blocked'));
    },
});
`;
    }
    return `// Generated by shipout fix — restrictive CORS
// Replace the wildcard '*' with your specific frontend origin(s).
// Example: Access-Control-Allow-Origin: https://yourapp.com
// CORS is not access control; real protection comes from authentication.
`;
}

export function writeFixes(fixes: GeneratedFix[], outDir: string): string[] {
    if (!fs.existsSync(outDir)) fs.mkdirSync(outDir, { recursive: true });
    const written: string[] = [];
    for (const fix of fixes) {
        const filePath = path.join(outDir, fix.filename);
        fs.writeFileSync(filePath, fix.content);
        written.push(filePath);
    }
    // README index
    const index = `# Shipout fixes\n\nGenerated from scan findings. Each file fixes one issue.\nReview each file, adapt to your codebase, then delete this directory.\n\n${fixes.map(f => `- \`${f.filename}\` — fixes: ${f.appliesTo}`).join('\n')}\n`;
    fs.writeFileSync(path.join(outDir, 'README.md'), index);
    written.push(path.join(outDir, 'README.md'));
    return written;
}
