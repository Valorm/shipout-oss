package fixer

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/valorm/shipout/scanner"
)

// Framework detected from project files
type Framework string

const (
	FrameworkExpress Framework = "express"
	FrameworkNextJS  Framework = "nextjs"
	FrameworkFastify Framework = "fastify"
	FrameworkKoa     Framework = "koa"
	FrameworkNode    Framework = "node"
	FrameworkUnknown Framework = "unknown"
)

// DetectFramework reads package.json to identify the web framework
func DetectFramework(dir string) Framework {
	data, err := os.ReadFile(filepath.Join(dir, "package.json"))
	if err != nil {
		return FrameworkUnknown
	}
	content := string(data)
	switch {
	case strings.Contains(content, `"next"`):
		return FrameworkNextJS
	case strings.Contains(content, `"express"`):
		return FrameworkExpress
	case strings.Contains(content, `"fastify"`):
		return FrameworkFastify
	case strings.Contains(content, `"koa"`):
		return FrameworkKoa
	default:
		return FrameworkNode
	}
}

// GeneratedFix is a single fix file to write
type GeneratedFix struct {
	Filename  string
	AppliesTo string
	Content   string
}

// Generate creates fix files from scan findings
func Generate(findings []scanner.Finding, fw Framework) []GeneratedFix {
	var fixes []GeneratedFix
	types := map[string]bool{}
	for _, f := range findings {
		types[f.Type] = true
	}

	if types["header_analysis"] {
		fixes = append(fixes, GeneratedFix{
			Filename:  "security-headers.js",
			AppliesTo: "Missing security headers",
			Content:   headersFix(fw),
		})
	}

	if hasExposed(findings, "/.env") {
		fixes = append(fixes, GeneratedFix{
			Filename:  ".gitignore.additions",
			AppliesTo: "Exposed .env file",
			Content:   "# Added by shipout fix — never commit secrets\n.env\n.env.local\n.env.production\n.env*.local\n",
		})
		fixes = append(fixes, GeneratedFix{
			Filename:  "ROTATE-SECRETS.md",
			AppliesTo: "Exposed .env file",
			Content:   rotationGuide(findings),
		})
	}

	if hasExposed(findings, "/debug") {
		fixes = append(fixes, GeneratedFix{
			Filename:  "REMOVE-DEBUG-ROUTE.md",
			AppliesTo: "Exposed /debug route",
			Content: `# Remove or protect the /debug route

Shipout found /debug publicly reachable and leaking config.

1. Delete the route entirely if it was for development only.
2. If you need it, gate it behind authentication and IP allowlisting:
   - Require an admin session
   - Only respond on localhost, never in production
   - Never include secrets, keys, or full environment dumps
`,
		})
	}

	if types["xss_probe"] {
		var endpoints []string
		for _, f := range findings {
			if f.Type == "xss_probe" && f.Endpoint != "" {
				endpoints = append(endpoints, f.Endpoint)
			}
		}
		fixes = append(fixes, GeneratedFix{
			Filename:  "escape-html.js",
			AppliesTo: "Reflected XSS",
			Content:   xssFix(endpoints),
		})
	}

	if types["cors_test"] {
		fixes = append(fixes, GeneratedFix{
			Filename:  "cors-config.js",
			AppliesTo: "Permissive CORS (informational)",
			Content:   corsFix(fw),
		})
	}

	if types["missing_timeout"] {
		fixes = append(fixes, GeneratedFix{
			Filename:  "timeout-helper.js",
			AppliesTo: "HTTP requests without timeouts",
			Content:   timeoutFix(fw),
		})
	}

	return fixes
}

func hasExposed(findings []scanner.Finding, path string) bool {
	for _, f := range findings {
		if f.Type == "sensitive_file_probe" {
			for _, e := range f.Evidence {
				if strings.Contains(e, path) {
					return true
				}
			}
		}
	}
	return false
}

// Write saves fixes to outDir and returns the written paths
func Write(fixes []GeneratedFix, outDir string) ([]string, error) {
	if err := os.MkdirAll(outDir, 0755); err != nil {
		return nil, err
	}

	var written []string
	for _, f := range fixes {
		p := filepath.Join(outDir, f.Filename)
		if err := os.WriteFile(p, []byte(f.Content), 0644); err != nil {
			return written, err
		}
		written = append(written, p)
	}

	index := "# Shipout fixes\n\nGenerated from scan findings. Each file fixes one issue.\nReview each file, adapt to your codebase, then delete this directory.\n\n"
	for _, f := range fixes {
		index += fmt.Sprintf("- `%s` — fixes: %s\n", f.Filename, f.AppliesTo)
	}
	ip := filepath.Join(outDir, "README.md")
	if err := os.WriteFile(ip, []byte(index), 0644); err != nil {
		return written, err
	}
	written = append(written, ip)

	return written, nil
}

func headersFix(fw Framework) string {
	headers := `    res.setHeader('X-Frame-Options', 'DENY');
    res.setHeader('X-Content-Type-Options', 'nosniff');
    res.setHeader('Strict-Transport-Security', 'max-age=31536000; includeSubDomains');
    res.setHeader('Content-Security-Policy', "default-src 'self'");
    res.setHeader('Referrer-Policy', 'strict-origin-when-cross-origin');`

	if fw == FrameworkExpress {
		return `// Generated by shipout fix — security headers middleware
// Usage: app.use(securityHeaders);

function securityHeaders(req, res, next) {
` + headers + `
    next();
}

module.exports = securityHeaders;
`
	}

	if fw == FrameworkNextJS {
		return `// Generated by shipout fix — add to next.config.js

const securityHeaders = [
  { key: 'X-Frame-Options', value: 'DENY' },
  { key: 'X-Content-Type-Options', value: 'nosniff' },
  { key: 'Strict-Transport-Security', value: 'max-age=31536000; includeSubDomains' },
  { key: 'Content-Security-Policy', value: "default-src 'self'" },
  { key: 'Referrer-Policy', value: 'strict-origin-when-cross-origin' },
];

// In next.config.js:
// async headers() {
//   return [{ source: '/(.*)', headers: securityHeaders }];
// }

module.exports = securityHeaders;
`
	}

	return "// Generated by shipout fix — add these headers to every response:\n\n" +
		strings.ReplaceAll(headers, "    ", "")
}

func rotationGuide(findings []scanner.Finding) string {
	var exposed []string
	for _, f := range findings {
		if f.Type == "sensitive_file_probe" {
			exposed = append(exposed, f.Evidence...)
		}
	}
	s := "# Rotate exposed secrets\n\nShipout found these files publicly reachable:\n"
	for _, e := range exposed {
		s += "- " + e + "\n"
	}
	s += `
Every secret in those files must be treated as compromised:

1. Generate new values for each secret (API keys, database URLs, tokens)
2. Update them in your hosting provider / secret manager
3. Redeploy the app
4. Revoke the old values at the provider
5. Check git history: if the file was ever committed, the secrets are in
   history forever. Rotate regardless of whether you delete the file now.
`
	return s
}

func xssFix(endpoints []string) string {
	return `// Generated by shipout fix — HTML escaping helper
// Reflected XSS found at: ` + strings.Join(endpoints, ", ") + `
// Never interpolate user input into HTML without escaping.

function escapeHtml(str) {
    return String(str)
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;')
        .replace(/"/g, '&quot;')
        .replace(/'/g, '&#39;');
}

// Before (vulnerable):
//   res.send(` + "`<h1>Results for: ${req.query.q}</h1>`" + `);

// After:
//   res.send(` + "`<h1>Results for: ${escapeHtml(req.query.q)}</h1>`" + `);

module.exports = escapeHtml;
`
}

func corsFix(fw Framework) string {
	if fw == FrameworkExpress {
		return `// Generated by shipout fix — restrictive CORS
// Only allow your own frontend origin. CORS is not access control;
// real protection comes from authentication.

const cors = require('cors');

const allowedOrigins = ['https://yourapp.com'];

module.exports = cors({
    origin: (origin, cb) => {
        if (!origin || allowedOrigins.includes(origin)) cb(null, true);
        else cb(new Error('CORS blocked'));
    },
});
`
	}
	return `// Generated by shipout fix — restrictive CORS
// Replace the wildcard '*' with your specific frontend origin(s).
// Example: Access-Control-Allow-Origin: https://yourapp.com
// CORS is not access control; real protection comes from authentication.
`
}

func timeoutFix(fw Framework) string {
	base := `// Generated by shipout fix — every outbound request gets a timeout.
// If the other side hangs, your request fails fast instead of freezing.

const DEFAULT_TIMEOUT_MS = 10000;

// Drop in replacement for fetch with a built in timeout.
// Usage: const res = await fetchWithTimeout("https://api.example.com/data");
async function fetchWithTimeout(url, options = {}) {
    const res = await fetch(url, {
        ...options,
        signal: options.signal || AbortSignal.timeout(options.timeoutMs || DEFAULT_TIMEOUT_MS),
    });
    return res;
}

// If you use axios, set the timeout once on the instance:
const axios = require('axios');
const api = axios.create({ timeout: DEFAULT_TIMEOUT_MS });
// Usage: const res = await api.get("https://api.example.com/data");

module.exports = { fetchWithTimeout, api, DEFAULT_TIMEOUT_MS };
`

	switch fw {
	case FrameworkExpress:
		return base + `
// Express: also cap how long the server waits on incoming requests.
// Put this where you create the server, after app.listen:

const server = app.listen(process.env.PORT || 3000);
server.setTimeout(30000);       // kill idle sockets after 30s
server.headersTimeout = 31000;  // must be above setTimeout
server.requestTimeout = 30000;  // cap full request duration
`
	case FrameworkNextJS:
		return base + `
// Next.js: use fetchWithTimeout inside route handlers and server actions.
// Route handlers already have platform limits, but your outbound calls
// still need their own timeout, which is what the helper above gives you.

// app/api/data/route.js
// import { fetchWithTimeout } from './timeout-helper';
// export async function GET() {
//     const res = await fetchWithTimeout("https://api.example.com/data");
//     return Response.json(await res.json());
// }
`
	case FrameworkFastify:
		return base + `
// Fastify: cap server timeouts where you create the instance:

// const fastify = require('fastify')({
//     connectionTimeout: 30000,
//     requestTimeout: 30000,
// });
`
	case FrameworkKoa:
		return base + `
// Koa: cap how long the server waits, where you create the server:

// const server = app.listen(process.env.PORT || 3000);
// server.setTimeout(30000);
// server.headersTimeout = 31000;
`
	default:
		return base
	}
}
